COLORS = {
    "cyan": "\033[96m",
    "blue": "\033[94m",
    "green": "\033[92m",
    "red": "\033[91m",
    "magenta": "\033[95m",
    "white": "\033[97m",
}
RESET = "\033[0m"


def clear_screen() -> None:
    os.system("cls" if os.name == "nt" else "clear")


def print_animation(delay: float, color: str | None, clear: bool) -> None:
    if clear:
        clear_screen()

    prefix = COLORS.get(color or "", "")
    suffix = RESET if prefix else ""

    for line in ART.splitlines():
        print(f"{prefix}{line}{suffix}", flush=True)
        time.sleep(delay)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Print an ASCII animation line by line.")
    parser.add_argument(
        "--delay",
        type=float,
        default=0.035,
        help="Delay between printed lines in seconds. Default: 0.035",
    )
    parser.add_argument(
        "--color",
        choices=sorted(COLORS),
        default="cyan",
        help="ANSI color for the animation. Default: cyan",
    )
    parser.add_argument(
        "--no-color",
        action="store_true",
        help="Disable ANSI color output.",
    )
    parser.add_argument(
        "--clear",
        action="store_true",
        help="Clear the terminal before printing.",
    )
    parser.add_argument(
        "--loop",
        action="store_true",
        help="Replay the animation until interrupted.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    color = None if args.no_color else args.color

    try:
        while True:
            print_animation(delay=max(args.delay, 0), color=color, clear=args.clear)
            if not args.loop:
                break
            time.sleep(0.8)
    except KeyboardInterrupt:
        print()
        return 130

    return 0


if __name__ == "__main__":
    sys.exit(main())
